'use strict';
const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('api', {
  load: () => ipcRenderer.invoke('data:load'),
  save: (data, opts) => ipcRenderer.invoke('data:save', data, opts),
  importFile: () => ipcRenderer.invoke('data:import'),
  exportFile: (data) => ipcRenderer.invoke('data:export', data),
  exportCsv: (name, text) => ipcRenderer.invoke('data:exportCsv', name, text),
  openFolder: () => ipcRenderer.invoke('data:openFolder'),
  chooseFolder: () => ipcRenderer.invoke('data:chooseFolder'),
  info: () => ipcRenderer.invoke('app:info'),
  update: () => ipcRenderer.invoke('app:update'),
  invoicePush: (jobs, absender, ziel, erzwingen) => ipcRenderer.invoke('invoice:push', jobs, absender, ziel, erzwingen),
  invoicePdf: (modell, absender) => ipcRenderer.invoke('invoice:pdf', modell, absender),
  openText: (titel, endungen) => ipcRenderer.invoke('file:openText', titel, endungen),
  savePdf: (html, opts) => ipcRenderer.invoke('pdf:save', html, opts),
  confirm: (text) => ipcRenderer.sendSync('dlg:confirm', String(text)),
  offertAlteWaehlen: () => ipcRenderer.invoke('offerte:alteWaehlen'),
  offertAnhangWaehlen: () => ipcRenderer.invoke('offerte:anhangWaehlen'),
  offertAnhangOeffnen: (datei) => ipcRenderer.invoke('offerte:anhangOeffnen', datei),
  offertAlteAblegen: (pfade) => ipcRenderer.invoke('offerte:alteAblegen', pfade),
  offertAnhangAblegen: (pfade) => ipcRenderer.invoke('offerte:anhangAblegen', pfade),
  pfadVon: (file) => { try { return webUtils.getPathForFile(file); } catch { return ''; } },
  offertDateiWeg: (art, datei, zurueck) => ipcRenderer.invoke('offerte:dateiWeg', art, datei, !!zurueck),
  offertOriginalLesen: (datei) => ipcRenderer.invoke('offerte:originalLesen', datei),
  offertOriginal: (datei) => ipcRenderer.invoke('offerte:original', datei),
  offertAgb: () => ipcRenderer.invoke('offerte:agb'),
  offertAgbSpeichern: (text) => ipcRenderer.invoke('offerte:agbSpeichern', text),
  offertBildWaehlen: (art) => ipcRenderer.invoke('offerte:bildWaehlen', art),
  offertBilder: (bilder) => ipcRenderer.invoke('offerte:bilder', bilder),
  openOfferte: () => ipcRenderer.invoke('offerte:open'),
  saveText: (text, opts) => ipcRenderer.invoke('text:save', text, opts),
  onChanged: (fn) => ipcRenderer.on('data:changed', () => fn()),
});
